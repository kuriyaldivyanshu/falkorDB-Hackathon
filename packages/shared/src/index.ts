/**
 * Public surface of `@threadline/shared`.
 *
 * This package holds wire contracts only: identity and association, sources,
 * accepted memory, coordination, context, operations/jobs and typed errors. It
 * must not import database clients, native harness code, filesystem modules or
 * hold credentials.
 *
 * There is exactly one definition per contract. Types are inferred from the
 * Zod schemas in each module, so a boundary cannot accept a field that is not
 * validated.
 */

